// NOTES

//1. PALINDROME
    // What is Palindrome?
        // A word/number that reads the same forward and backward.
        // Examples:
        // madam, racecar, 121, 1221
    
    // Approach to solve
        // Two common approaches:
            // Reverse the string and compare
            // Compare first & last characters moving inward

// 2. FIBONACCI
    // What is Fibonacci?
        // A series where each number is sum of previous two:
        // 0, 1, 1, 2, 3, 5, 8, 13...
        // F(n) = F(n-1) + F(n-2)
    // Approach to solve
        // Recursive

// 3. FACTORIAL
    // What is Factorial?
        // Multiplication of all numbers from 1 to N.
        // 5! = 5 × 4 × 3 × 2 × 1 = 120
    // Approach
        // Multiply numbers from 1 to N
    
//4. PRIME NUMBER
    // What is Prime?
        // A number divisible only by:
        // 1 and itself
        // Examples: 2,3,5,7,11,13
        // Not prime: 4,6,8,9

// 5. ANAGRAM
    // What is Anagram?
        // Two strings having same letters in different order
        // Examples:
            // listen ↔ silent
            // evil ↔ vile
    // Approach
        // Sort both strings and compare
        // Count characters
